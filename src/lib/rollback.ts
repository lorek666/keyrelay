/**
 * 回滚成功之后必须告诉用户的事（M9-S4 复审 P2-1 / BACKLOG B-125）。
 *
 * 回滚只还原文件、不动绑定。只要那个 agent 还绑着，漂移检测拿「KeyRelay 最后写下的内容」去比，
 * 回滚后的文件必然对不上：总览会一直把它列为「需要处理」，每打开一次总览还会记一条
 * 「外部改动」告警；轮换这把密钥时它会被重新写入，批量改指网关时它也仍在候选里（逐条勾选，默认不勾）。
 * 这是 M3-S1 的既定语义（改不改由 B-125 决定）——在那之前，至少要把后果说全。
 *
 * 投递页与历史页两处回滚共用这一句：此前两处说法不一，投递页那处一个字都没提。
 */
export function rollbackAftermath(agentId: string): string {
  return (
    `只要 ${agentId} 还绑着，「总览」就会一直把这个目标列为「需要处理」，每打开一次总览还会记一条「外部改动」告警——` +
    "文件已经不是 KeyRelay 写入的内容，这是预期的，不要据此重新投递（那等于撤销这次回滚）；" +
    "轮换这把密钥时，这个文件会被重新写入；批量改指网关时它也仍在候选里。" +
    `不想再让 KeyRelay 管它，到「Agent 投递」页解绑 ${agentId}。`
  );
}
